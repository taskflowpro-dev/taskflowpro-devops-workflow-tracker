-- Repository children carry a composite workspace FK so records cannot be linked
-- to a repository in another workspace even outside the application service.
ALTER TABLE tracked_repositories ADD CONSTRAINT uk_repository_workspace UNIQUE (id, workspace_id);

CREATE TABLE devops_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id),
    signal_key VARCHAR(60) NOT NULL,
    title VARCHAR(200) NOT NULL,
    explanation TEXT NOT NULL,
    evidence TEXT NOT NULL,
    priority VARCHAR(10) NOT NULL CHECK (priority IN ('HIGH','MEDIUM','LOW')),
    complexity VARCHAR(20) NOT NULL,
    observed_status VARCHAR(20) NOT NULL CHECK (observed_status IN ('PRESENT','MISSING','UNKNOWN')),
    analyzed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (repository_id, workspace_id) REFERENCES tracked_repositories(id, workspace_id) ON DELETE CASCADE,
    UNIQUE (repository_id, signal_key),
    UNIQUE (id, workspace_id)
);

CREATE TABLE implementation_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id BIGINT NOT NULL REFERENCES devops_recommendations(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL,
    instructions TEXT NOT NULL,
    file_path VARCHAR(300) NOT NULL DEFAULT '',
    command TEXT NOT NULL DEFAULT '',
    validation TEXT NOT NULL,
    troubleshooting TEXT NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_by BIGINT REFERENCES users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (recommendation_id, position)
);

CREATE TABLE generated_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id),
    kind VARCHAR(30) NOT NULL CHECK (kind IN ('workflow','docker','deployment','security')),
    file_path VARCHAR(300) NOT NULL,
    content TEXT NOT NULL CHECK (length(content) <= 65536),
    metadata JSONB NOT NULL DEFAULT '{}',
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (repository_id, workspace_id) REFERENCES tracked_repositories(id, workspace_id) ON DELETE CASCADE
);
CREATE INDEX idx_configurations_workspace_repository ON generated_configurations(workspace_id, repository_id, created_at DESC);

CREATE TABLE deployment_environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id),
    name VARCHAR(80) NOT NULL,
    target VARCHAR(30) NOT NULL CHECK (target IN ('ubuntu-vps','managed-cloud')),
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED','REVIEWED')),
    plan JSONB NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (repository_id, workspace_id) REFERENCES tracked_repositories(id, workspace_id) ON DELETE CASCADE
);
CREATE INDEX idx_environments_workspace_repository ON deployment_environments(workspace_id, repository_id);

CREATE TABLE ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id),
    title VARCHAR(160) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (repository_id, workspace_id) REFERENCES tracked_repositories(id, workspace_id) ON DELETE CASCADE,
    UNIQUE (id, workspace_id)
);
CREATE INDEX idx_conversations_workspace_repository ON ai_conversations(workspace_id, repository_id, created_at DESC);
CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('user','assistant')),
    content TEXT NOT NULL CHECK (length(content) <= 24000),
    source VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_messages_conversation ON ai_messages(conversation_id, id);

CREATE TABLE user_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    compact_mode BOOLEAN NOT NULL DEFAULT FALSE,
    reduce_motion BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE workspace_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    action VARCHAR(100) NOT NULL,
    detail VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_activity_workspace_date ON workspace_activity(workspace_id, created_at DESC, id DESC);
