UPDATE tasks t SET workspace_id = w.id FROM workspaces w WHERE w.kind = 'PERSONAL' AND w.owner_id = t.created_by;
UPDATE deployments d SET workspace_id = w.id FROM workspaces w WHERE w.kind = 'PERSONAL' AND w.owner_id = d.deployed_by;
